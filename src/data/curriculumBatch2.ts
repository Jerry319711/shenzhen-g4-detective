import { ClueToken, DetectiveCase, MathVisualSpec, SkillCategory } from '../types';

// 精炼构造器：保证每一宗案件都具备完整的深圳四年级线索放大镜、3级免费锦囊、温柔分项反馈与神探口诀
interface EngFillSpec {
  id: string;
  skill: SkillCategory;
  diff: 1 | 2 | 3;
  ref: string;
  title: string;
  suspect: string;
  story: string;
  readAloud: string;
  clueGoal: string;
  tokens: ClueToken[];
  prompt: string;
  options: string[];
  correctIndex: number;
  feedback: string[];
  hints: [string, string, string];
  rule: string;
  cardId?: string;
}

function makeEngFill(s: EngFillSpec): DetectiveCase {
  return {
    id: s.id,
    subject: 'english',
    skill: s.skill,
    mode: 'eng_clue_fill',
    difficulty: s.diff,
    textbookRef: s.ref,
    title: s.title,
    suspectName: s.suspect,
    storyIntro: s.story,
    readAloudText: s.readAloud,
    clueGoalText: s.clueGoal,
    tokens: s.tokens,
    steps: [
      {
        prompt: s.prompt,
        options: s.options,
        correctIndex: s.correctIndex,
        optionFeedback: s.feedback,
        hints: s.hints,
      },
    ],
    goldenRule: s.rule,
    rewardStars: s.diff === 1 ? 15 : s.diff === 2 ? 18 : 22,
    cardId: s.cardId,
  };
}

interface EngBugSpec extends EngFillSpec {}
function makeEngBug(s: EngBugSpec): DetectiveCase {
  return { ...makeEngFill(s), mode: 'eng_spot_bug' };
}

interface MathSpec {
  id: string;
  skill: SkillCategory;
  diff: 1 | 2 | 3;
  ref: string;
  title: string;
  suspect: string;
  story: string;
  clueGoal: string;
  tokens: ClueToken[];
  visual?: MathVisualSpec;
  step1: { prompt: string; options: string[]; correctIndex: number; feedback: string[]; hints: [string, string, string] };
  step2: { prompt: string; options: string[]; correctIndex: number; feedback: string[]; hints: [string, string, string] };
  rule: string;
  cardId?: string;
}

function makeMath(s: MathSpec): DetectiveCase {
  return {
    id: s.id,
    subject: 'math',
    skill: s.skill,
    mode: 'math_scaffold',
    difficulty: s.diff,
    textbookRef: s.ref,
    title: s.title,
    suspectName: s.suspect,
    storyIntro: s.story,
    clueGoalText: s.clueGoal,
    tokens: s.tokens,
    visual: s.visual,
    steps: [
      { ...s.step1, optionFeedback: s.step1.feedback, visualStage: 1 },
      { ...s.step2, optionFeedback: s.step2.feedback, visualStage: 2 },
    ],
    goldenRule: s.rule,
    rewardStars: s.diff === 1 ? 16 : s.diff === 2 ? 20 : 25,
    cardId: s.cardId,
  };
}

