import { ClueToken, DetectiveCase, MathVisualSpec, SkillCategory } from '../types';

interface EngSpec {
  id: string;
  skill: SkillCategory;
  mode?: 'eng_clue_fill' | 'eng_spot_bug';
  diff: 1 | 2 | 3;
  ref: string;
  title: string;
  suspect: string;
  story: string;
  readAloud: string;
  clueGoal: string;
  tokens: ClueToken[];
  prompt: string;
  options: string[];
  correctIndex: number;
  feedback: string[];
  hints: [string, string, string];
  rule: string;
  cardId?: string;
}

function makeEng(s: EngSpec): DetectiveCase {
  return {
    id: s.id,
    subject: 'english',
    skill: s.skill,
    mode: s.mode || 'eng_clue_fill',
    difficulty: s.diff,
    textbookRef: s.ref,
    title: s.title,
    suspectName: s.suspect,
    storyIntro: s.story,
    readAloudText: s.readAloud,
    clueGoalText: s.clueGoal,
    tokens: s.tokens,
    steps: [
      {
        prompt: s.prompt,
        options: s.options,
        correctIndex: s.correctIndex,
        optionFeedback: s.feedback,
        hints: s.hints,
      },
    ],
    goldenRule: s.rule,
    rewardStars: s.diff === 1 ? 7 : s.diff === 2 ? 9 : 12,
    cardId: s.cardId,
  };
}

interface MathSpec {
  id: string;
  skill: SkillCategory;
  diff: 1 | 2 | 3;
  ref: string;
  title: string;
  suspect: string;
  story: string;
  clueGoal: string;
  tokens: ClueToken[];
  visual?: MathVisualSpec;
  step1: { prompt: string; options: string[]; correctIndex: number; feedback: string[]; hints: [string, string, string] };
  step2: { prompt: string; options: string[]; correctIndex: number; feedback: string[]; hints: [string, string, string] };
  rule: string;
  cardId?: string;
}

function makeMath(s: MathSpec): DetectiveCase {
  return {
    id: s.id,
    subject: 'math',
    skill: s.skill,
    mode: 'math_scaffold',
    difficulty: s.diff,
    textbookRef: s.ref,
    title: s.title,
    suspectName: s.suspect,
    storyIntro: s.story,
    clueGoalText: s.clueGoal,
    tokens: s.tokens,
    visual: s.visual,
    steps: [
      { ...s.step1, optionFeedback: s.step1.feedback, visualStage: 1 },
      { ...s.step2, optionFeedback: s.step2.feedback, visualStage: 2 },
    ],
    goldenRule: s.rule,
    rewardStars: s.diff === 1 ? 8 : s.diff === 2 ? 10 : 12,
    cardId: s.cardId,
  };
}

